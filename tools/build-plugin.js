#!/usr/bin/env node
// repo · tools/build-plugin.js
// Packages this repo's Claude setup (.claude/ + .mcp.json) as a Claude Code plugin + marketplace,
// so another computer or another repo can install it with /plugin.
//   Source of truth: .claude/ (edit there, never in plugins/).  Output: plugins/<name>/ (generated)
//   and .claude-plugin/marketplace.json.
// Usage: node tools/build-plugin.js [--version 0.2.0]
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const NAME = 'powerbi-delivery-kit';
const MARKETPLACE = 'powerbi-kit';
const OWNER = 'Power BI Delivery Kit';
const DESCRIPTION = 'Power BI delivery: shared design + data → state.json → HTML mockup, Power BI report (TMDL model + PBIR pages) and interactive HTML twin. Includes the vendored Microsoft powerbi-authoring skills and the Power BI Modeling MCP.';
const OUT = path.join(ROOT, 'plugins', NAME);
const MARK = 'GENERATED by tools/build-plugin.js — edit .claude/ instead';

const args = {};
for (let i = 2; i < process.argv.length; i += 2) args[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];

// keep the current version unless one is given
const manifestPath = path.join(OUT, '.claude-plugin', 'plugin.json');
const prev = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : null;
if (fs.existsSync(OUT) && !fs.existsSync(path.join(OUT, '.claude-plugin', 'GENERATED'))) { console.error(`ERROR ${OUT} was not generated by this script — not touching it.`); process.exit(1); }
const version = args.version || (prev && prev.version) || '0.1.0';

fs.rmSync(OUT, { recursive: true, force: true });
const src = (p) => path.join(ROOT, '.claude', p);
const copy = (from, to) => fs.cpSync(from, path.join(OUT, to), { recursive: true });
copy(src('skills'), 'skills');
copy(src('agents'), 'agents');
copy(src('common'), 'common'); // vendored skills link ../../common/...
copy(src('commands'), 'commands');
fs.copyFileSync(path.join(ROOT, '.mcp.json'), path.join(OUT, '.mcp.json'));

// commands name the skill by its repo path; in a plugin it lives elsewhere
const NOTE = '> `<pbi-delivery>` = the folder of this plugin\'s `pbi-delivery` skill (its base directory is shown when the skill loads).\n\n';
let rewritten = 0;
for (const f of fs.readdirSync(path.join(OUT, 'commands'))) {
  const p = path.join(OUT, 'commands', f);
  const s = fs.readFileSync(p, 'utf8');
  if (!s.includes('.claude/skills/pbi-delivery/')) continue;
  const t = s.replace(/\.claude\/skills\/pbi-delivery\//g, '<pbi-delivery>/').replace(/^(---\n[\s\S]*?\n---\n\n?)/, `$1${NOTE}`);
  fs.writeFileSync(p, t); rewritten++;
}

fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
const manifest = {
  name: NAME,
  version,
  description: DESCRIPTION,
  author: { name: OWNER },
  keywords: ['power-bi', 'pbip', 'tmdl', 'pbir', 'dashboard', 'mockup'],
};
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
// marker kept outside the manifest so validation sees only known fields
fs.writeFileSync(path.join(OUT, '.claude-plugin', 'GENERATED'), MARK + '\n');

const cmds = fs.readdirSync(path.join(OUT, 'commands')).map((f) => '`/' + f.replace(/\.md$/, '') + '`').join(' · ');
fs.writeFileSync(path.join(OUT, 'README.md'), `# ${NAME}

${DESCRIPTION}

> ${MARK}. Built from version ${version}.

## Install

\`\`\`
/plugin marketplace add <clone path or git URL of the kit repo>
/plugin install ${NAME}@${MARKETPLACE}
\`\`\`
Restart Claude Code, then run \`/setup\` once on each computer.

## Contents

- Skills: \`pbi-delivery\` (method + scripts), \`semantic-model-authoring\` and \`powerbi-report-cli\` (vendored, see \`common/VENDORED.md\`).
- Commands: ${cmds}.
- Agent: \`model-reviewer\`.
- MCP: \`powerbi-modeling-mcp\` (via \`npx\`; accept its EULA once).

## Requirements

Node.js 20+, Power BI Desktop, Git, \`npm install -g @microsoft/powerbi-report-authoring-cli@latest\`.
`);

const market = {
  name: MARKETPLACE,
  owner: { name: OWNER },
  metadata: { description: 'Claude Code plugins for Power BI delivery' },
  plugins: [{ name: NAME, source: `./plugins/${NAME}`, description: DESCRIPTION, version }],
};
fs.mkdirSync(path.join(ROOT, '.claude-plugin'), { recursive: true });
fs.writeFileSync(path.join(ROOT, '.claude-plugin', 'marketplace.json'), JSON.stringify(market, null, 2) + '\n');

console.log(JSON.stringify({ ok: true, plugin: path.relative(ROOT, OUT), version, commandsRewritten: rewritten }, null, 2));
